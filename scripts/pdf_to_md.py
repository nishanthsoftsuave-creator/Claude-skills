import hashlib
import json
import re
import shutil
import sys
import warnings
from collections import Counter
from itertools import groupby
from pathlib import Path

warnings.filterwarnings("ignore")
import pymupdf  # noqa: E402

from build_matrix import slug  # noqa: E402

MARK = "Generated by `scripts/pdf_to_md.py`"
CHAR_FIX = str.maketrans({"ﬁ": "fi", "ﬂ": "fl", "ﬀ": "ff", "ﬃ": "ffi", "ﬄ": "ffl", "­": "", " ": " ", "​": ""})
READABLE = re.compile(r"[\x20-\x7e -ÿ–—‘-”•…™€✓◻□➤]")
STOP = {"the", "of", "and", "a", "an", "to", "for", "in", "vs"}
GLYPHS = "•◻□✓"
ROW_MAX = 160  # points; a table row taller than this is not trusted (see _grid)
CHAPTER = re.compile(r"^Chapter\s+(\d+)\s*[:.\-–]\s*(.*)$", re.I)
CAPTION = re.compile(r"^\W*(Figure|Table)\s+\d")
SQUARED = re.compile(r"(?:\b[kcm]?m|\bft|\bmi|\bISC)\s*$")
SENTENCE_END = re.compile(r"""[.!?:;]["”’')\]]*(\[\^\d+\])*$""")
FIGURE = "*[Figure omitted]*"
FIGURE_TEXT = "*[Text inside a figure could not be extracted]*"


def _norm(s):
    s = s.translate(CHAR_FIX).replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"').replace("…", "...")
    return re.sub(r"\s+", " ", s).strip().casefold()


def _short(title, n=40):
    """Folder-name slug: leading article and trailing stop words dropped, cut at a word boundary."""
    s = slug(title)
    if len(s) > n:
        s = s[:n] if s[n] == "-" else s[:n].rsplit("-", 1)[0]
    parts = s.split("-")
    while len(parts) > 1 and parts[0] in ("the", "a", "an"):
        parts.pop(0)
    while len(parts) > 1 and parts[-1] in STOP:
        parts.pop()
    return "-".join(parts)


def _span(a, b):
    return f"PDF p. {a}" if a == b else f"PDF pp. {a}-{b}"


# ---- outline -------------------------------------------------------------------------------------

class Node:
    def __init__(self, level, title, page):
        self.level, self.page, self.kids, self.end = level, page, [], page
        self.title = re.sub(r"\s+", " ", title.translate(CHAR_FIX)).strip()


def outline(doc):
    """Outline tree; node.end is the start page of the next entry at the same or a higher level (exclusive at the end)."""
    roots, stack = [], []
    for level, title, page in doc.get_toc():
        n = Node(level, title, page)
        while stack and stack[-1].level >= level:
            stack.pop()
        (stack[-1].kids if stack else roots).append(n)
        stack.append(n)

    def ends(nodes, limit):
        for i, n in enumerate(nodes):
            n.end = nodes[i + 1].page if i + 1 < len(nodes) else limit
            ends(n.kids, n.end)

    ends(roots, doc.page_count + 1)
    return roots


def plan(roots, skip, max_pages):
    """Files to write, in book order: dicts {node, kind: intro|lead|section, folder, label, top}; plus skipped nodes."""
    units, skipped = [], []
    first_chapter = next((n.page for n in roots if CHAPTER.match(n.title)), 0)

    def split(node, top, folder, label):
        if node.end - node.page + 1 <= max_pages or not node.kids:
            units.append({"node": node, "kind": "section", "top": top, "folder": folder, "label": label})
            return
        units.append({"node": node, "kind": "lead", "top": top, "folder": folder, "label": label})
        for k in node.kids:
            split(k, top, folder, label)

    for n in roots:
        if n.title.casefold() in skip:
            skipped.append(n)
        elif (m := CHAPTER.match(n.title)):
            folder = f"ch{int(m[1]):02d}-{_short(m[2])}"
            units.append({"node": n, "kind": "intro" if n.kids else "section", "top": n.title, "folder": folder,
                          "label": m[1]})
            for k in n.kids:
                split(k, n.title, folder, m[1])
        else:
            split(n, "Front and back matter", "front-back-matter", "front" if n.page < first_chapter else "back")
    return units, skipped


# ---- one page -> items ---------------------------------------------------------------------------

def _md(spans, size, emphasis=True):
    """Markdown for a run of spans: bold and italic as ** and *, a small superscript number as a footnote reference."""
    segs = []
    for s in spans:
        t = s["text"].translate(CHAR_FIX)
        if re.fullmatch(r"\d{1,3}", t.strip()) and s["size"] < 0.75 * size:
            squared = t.strip() in ("2", "3") and SQUARED.search("".join(x[0] for x in segs))  # km2, m3, ISC2
            t, style = ("²" if t.strip() == "2" else "³") if squared else f"[^{t.strip()}]", 0
        else:
            style = ((1 if (s["flags"] & 16) else 0) + (2 if (s["flags"] & 2) else 0)) if emphasis else 0
        if segs and segs[-1][1] == style:
            segs[-1][0] += t
        else:
            segs.append([t, style])
    out = ""
    for t, style in segs:
        mark = ("", "**", "*", "***")[style] if t.strip() else ""
        out += f"{t[:len(t) - len(t.lstrip())]}{mark}{t.strip()}{mark}{t[len(t.rstrip()):]}" if mark else t
    return out


def _line(ln):
    spans = ln["spans"]
    size = round(max(s["size"] for s in spans), 1)
    first = next((s for s in spans if s["text"].strip()), spans[0])
    return {"raw": "".join(s["text"] for s in spans).translate(CHAR_FIX), "md": _md(spans, size), "size": size,
            "lead": first["text"].strip(), "lead_size": first["size"], "spans": spans}


def _join(lines, vocab):
    """Join wrapped lines; a line-end hyphen is kept in URLs and real compounds, dropped inside split words."""
    out = lines[0]
    for nxt in lines[1:]:
        if not (out.endswith("-") and not out.endswith(" -") and nxt[:1].isalnum()):
            out += " " + nxt
            continue
        last = out.split()[-1]
        a, b = last.rstrip("-").lower(), (re.match(r"[A-Za-z]+", nxt) or [""])[0].lower()
        split_word = a.isalpha() and nxt[:1].islower() and f"{a}-{b}" not in vocab[1] and (a + b) in vocab[0]
        out = out[:-1] + nxt if split_word and "/" not in last else out + nxt
    out = re.sub(r"\*\*(\s+)\*\*", r"\1", re.sub(r" {2,}", " ", out))  # one bold or italic run per wrapped paragraph
    return re.sub(r"(?<!\*)\*(\s+)\*(?!\*)", r"\1", out)


def _garbled(text):
    """Control codes or mostly non-text characters: figure text in a font whose encoding is broken."""
    t = text.strip()
    return bool(re.search(r"[\x00-\x08\x0b-\x1f]", t)) or (len(t) > 2 and sum(1 for c in t if not READABLE.match(c)) >= 0.25 * len(t))


def _disp(page, bbox):
    """A raw text or image box in displayed coordinates (find_tables works there; they differ on rotated pages)."""
    r = pymupdf.Rect(bbox) * page.rotation_matrix
    r.normalize()
    return r


def _centre_in(r, box):
    cx, cy = (r.x0 + r.x1) / 2, (r.y0 + r.y1) / 2
    return box.x0 - 2 <= cx <= box.x1 + 2 and box.y0 - 2 <= cy <= box.y1 + 2


def _cell(texts, vocab):
    """One table cell from its lines: a bullet, check box or capitalised line starts a new item, a lower-case line wraps."""
    segs = []
    for t in texts:
        if not segs or t[0] in GLYPHS or not t[0].islower():
            segs.append([t])
        else:
            segs[-1].append(t)
    return "<br>".join(_join(s, vocab) for s in segs).replace("|", "\\|")


def _grid(page, recs, vocab):
    """Pipe tables: [(rect, markdown, records used)]. find_tables gives the area and the column edges; the cells are
    rebuilt from the page's own text lines. Blocks that start at the same height form a row, and a block with nothing
    in the first column continues the row above. A table whose rows come out taller than ROW_MAX (the blocks are
    columns, not rows) is left as flowing text rather than risk pairing the wrong cells."""
    out = []
    for t in page.find_tables().tables:
        rect = pymupdf.Rect(t.bbox)
        mine = [r for r in recs if _centre_in(r["disp"], rect)]
        edges = []
        for x in sorted(c[0] for c in t.cells):
            if not edges or x - edges[-1] > 4:
                edges.append(x)
        blocks = {}
        for r in mine:
            blocks.setdefault(r["b"], []).append(r)
        clusters = []  # [top, lines]
        for top, rs in sorted(((min(r["disp"].y0 for r in rs), rs) for rs in blocks.values()), key=lambda p: p[0]):
            if clusters and top - clusters[-1][0] <= 3:
                clusters[-1][1] += rs
            else:
                clusters.append([top, list(rs)])
        rows = []  # [top, bottom, {column: [lines of text]}]
        for top, rs in clusters:
            cells = {}
            for r in sorted(rs, key=lambda r: (r["disp"].y0, r["disp"].x0)):
                col = max((i for i, x in enumerate(edges) if x <= r["disp"].x0 + 4), default=0)
                cells.setdefault(col, []).append(_md(r["spans"], r["size"], False).strip())
            bottom = max(r["disp"].y1 for r in rs)
            if rows and 0 not in cells:
                rows[-1][1] = max(rows[-1][1], bottom)
                for col, texts in cells.items():
                    rows[-1][2].setdefault(col, []).extend(texts)
            else:
                rows.append([top, bottom, cells])
        cols = sorted({c for *_, cells in rows for c in cells})
        if len(rows) >= 2 and len(cols) >= 2 and all(b - tp <= ROW_MAX for tp, b, _ in rows):
            grid = [[_cell(cells[c], vocab) if c in cells else "" for c in cols] for *_, cells in rows]
            md = ["| " + " | ".join(grid[0]) + " |", "|" + "---|" * len(cols)] + ["| " + " | ".join(g) + " |" for g in grid[1:]]
            out.append((rect, "\n".join(md), mine))
    return out


def page_items(page, drop_title, head_min, vocab):
    """One page -> (items, footnotes, printed page number). Items: h / p / li / table / img / note, in reading order."""
    raw_h = page.mediabox.height  # the header and footer sit in the raw margins, also on rotated pages
    recs, images, items, notes, printed, bad_y = [], [], [], [], None, None
    blocks = page.get_text("dict")["blocks"]
    bad_fonts = {s["font"] for b in blocks if b["type"] == 0 for ln in b["lines"] for s in ln["spans"] if _garbled(s["text"])}
    for bi, b in enumerate(blocks):
        if b["type"] == 1:
            d = _disp(page, b["bbox"])
            if min(d.width, d.height) >= 40:
                images.append(d)
            continue
        for ln in b["lines"]:
            L = _line(ln)
            L["txt"] = L["raw"].strip()
            y0 = ln["bbox"][1]
            if not L["txt"]:
                continue
            if y0 >= 0.91 * raw_h:  # page number and print footer
                printed = L["txt"] if re.fullmatch(r"[ivxlc]+|\d{1,4}", L["txt"], re.I) else printed
            elif not (y0 < 0.092 * raw_h and L["size"] <= 10.5):  # running title
                L.update(b=bi, disp=_disp(page, ln["bbox"]), dir=(round(ln["dir"][0]), round(ln["dir"][1])),
                         fonts={s["font"] for s in ln["spans"] if s["text"].strip()})
                recs.append(L)
    weight = Counter()
    for r in recs:
        weight[r["dir"]] += len(r["txt"])
    main_dir = weight.most_common(1)[0][0] if weight else None
    kept = []
    for r in recs:
        if r["dir"] != main_dir:  # sideways labels
            continue
        if r["size"] < 8 or r["fonts"] <= bad_fonts or _garbled(r["txt"]):  # figure text
            bad_y = r["disp"].y0 if bad_y is None else bad_y
        elif not (drop_title and r["size"] >= head_min and _norm(r["txt"]) in drop_title):
            kept.append(r)
    tables = _grid(page, kept, vocab)
    used = {id(r) for _, _, rs in tables for r in rs}
    kept = [r for r in kept if id(r) not in used]
    for _, grp in groupby(kept, key=lambda r: r["b"]):
        lines = list(grp)
        first = lines[0]
        if re.fullmatch(r"\d{1,3}", first["lead"]) and first["lead_size"] < 7.5 and first["size"] <= 10.5 \
                and first["disp"].y0 > page.rect.height / 2:  # footnote: number in a small span, then the note
            parts = [first["txt"][len(first["lead"]):].strip()] + [x["txt"] for x in lines[1:]]
            note = parts[0]
            for t in parts[1:]:
                note += t if note.endswith(("-", "_", "/")) else " " + t
            notes.append({"k": "fn", "n": first["lead"], "text": note})
            continue
        segs = []
        for L in lines:
            kind = "h" if L["size"] >= head_min else "p"
            if segs and segs[-1][0] == kind and (kind == "p" or segs[-1][1][-1]["size"] == L["size"]):
                segs[-1][1].append(L)
            else:
                segs.append((kind, [L]))
        for kind, ls in segs:
            y, x = ls[0]["disp"].y0, ls[0]["disp"].x0
            if kind == "h":
                items.append({"k": "h", "y": y, "size": ls[0]["size"],
                              "text": _join([_md(r["spans"], r["size"], False).strip() for r in ls], vocab)})
                continue
            groups = []  # a list marker (alone on its line, or an inline bullet) starts a list item; other lines wrap
            for r in ls:
                text = r["md"].strip()
                m = re.match(r"^(•|\d{1,2}\.)(?:\s+(.*))?$", text)
                if m and (m[1] == "•" or not m[2]):
                    groups.append({"mark": m[1], "texts": [m[2]] if m[2] else [], "lines": [r]})
                elif groups:
                    groups[-1]["texts"].append(text)
                    groups[-1]["lines"].append(r)
                else:
                    groups.append({"mark": None, "texts": [text], "lines": [r]})
            for g in groups:
                first, rest = g["lines"][0], g["lines"][1:]
                if g["mark"] is None:
                    items.append({"k": "p", "y": first["disp"].y0, "x": first["disp"].x0, "size": first["size"],
                                  "text": _join(g["texts"], vocab), "rest": min((r["disp"].x0 for r in rest), default=None)})
                elif g["texts"]:
                    items.append({"k": "li", "y": first["disp"].y0, "x": first["disp"].x0, "text": _join(g["texts"], vocab),
                                  "mark": "-" if g["mark"] == "•" else g["mark"]})
    paras = [i for i in items if i["k"] == "p"]
    base = min([i["rest"] for i in paras if i["rest"] is not None] or [i["x"] for i in paras] or [0])
    for i in paras:
        i["indent"] = i["x"] >= base + 8  # a first line indented from the left margin starts a paragraph
    floats = [{"k": "img", "y": d.y0, "text": FIGURE} for d in images if not any(_centre_in(d, r) for r, _, _ in tables)]
    floats += [{"k": "table", "y": r.y0, "text": md} for r, md, _ in tables]
    if bad_y is not None:
        floats.append({"k": "note", "y": bad_y, "text": FIGURE_TEXT})
    for f in sorted(floats, key=lambda f: f["y"]):
        items.insert(next((i for i, it in enumerate(items) if it["y"] > f["y"]), len(items)), f)
    return items, sorted(notes, key=lambda n: int(n["n"])), printed


# ---- whole book ----------------------------------------------------------------------------------

def vocabulary(doc, pages):
    """(plain words, hyphenated words) seen in the text, to decide whether a line-end hyphen is part of the word."""
    plain, hyphen = set(), set()
    for n in pages:
        for w in re.findall(r"[A-Za-z]+(?:-[A-Za-z]+)*", doc[n - 1].get_text()):
            (hyphen if "-" in w else plain).add(w.lower())
    return plain, hyphen


def _place_notes(items, notes):
    """Footnote texts go before the next heading after the text that cites them, so a section keeps its own notes."""
    at = {}
    for fn in notes:
        i = max((i for i, it in enumerate(items) if f"[^{fn['n']}]" in it.get("text", "")), default=len(items) - 1)
        at.setdefault(next((j for j in range(i + 1, len(items)) if items[j]["k"] == "h"), len(items)), []).append(fn)
    out = []
    for j, it in enumerate(items + [None]):
        out += at.get(j, [])
        out += [it] if it else []
    return out


def build_stream(doc, pages, titles, head_min):
    vocab, stream, printed = vocabulary(doc, pages), [], {}
    for n in pages:
        items, notes, printed[n] = page_items(doc[n - 1], titles.get(n), head_min, vocab)
        items = _place_notes(items, notes)
        for it in items:
            it["page"] = n
        stream += items
    merged = []
    for it in stream:  # an unfinished paragraph continues in the next block: over a page break (inline marker) or a wrapped line
        j = len(merged) - 1
        while j >= 0 and merged[j]["k"] == "fn":
            j -= 1
        prev = merged[j] if j >= 0 else None
        if (it["k"] == "p" and prev and prev["k"] == "p" and prev["size"] == it["size"]
                and not CAPTION.match(it["text"]) and not CAPTION.match(prev["parts"][0][1])
                and ((prev["page"] == it["page"] - 1 and not it["indent"] and it["page"] not in titles)
                     or (prev["page"] == it["page"] and it["text"][:1].islower()))
                and not SENTENCE_END.search(prev["parts"][-1][1])):
            last_page, last_text = prev["parts"][-1]
            if last_text.endswith("-") and not last_text.endswith(" -"):  # a word split by a hyphen: glue the pieces
                prev["parts"][-1] = (last_page, _join([last_text, it["text"]], vocab))
                if it["page"] != last_page:
                    prev.setdefault("trail", []).append(it["page"])  # the marker for the new page goes after the word
            else:
                prev["parts"].append((it["page"], it["text"]))
            prev["page"] = it["page"]
            continue
        if it["k"] == "p":
            it["parts"] = [(it["page"], it["text"])]
        merged.append(it)
    return merged, printed


def locate(stream, node, cursor):
    """Index of the heading that opens an outline entry (exact title, then a prefix match), searching forward."""
    want = _norm(node.title)
    for loose in (False, True):
        for i in range(cursor, len(stream)):
            it = stream[i]
            if it["page"] > node.page + 2:
                break
            if it["page"] >= node.page and it["k"] == "h":
                have = _norm(re.sub(r"\[\^\d+\]", "", it["text"]))
                if have == want or (loose and (want.startswith(have) or have.startswith(want))):
                    return i
    return None


def marker(page, printed):
    book = f" (book p. {printed[page]})" if printed.get(page) else ""
    return f"<!-- PDF p. {page}{book} -->"


def render(items, root_size, ranks, printed):
    """Markdown body for a slice of the stream."""
    blocks, page, stack = [], None, []
    for it in items:
        k = it["k"]
        opens = it["parts"][0][0] if k == "p" else it["page"]
        if k != "fn" and opens != page:
            blocks.append(("marker", marker(opens, printed)))
            stack = []  # the left margin changes from page to page: list depth starts again
        if k == "p":
            text, last = it["parts"][0][1], it["parts"][0][0]
            for pg, t in it["parts"][1:]:
                text += (f" {marker(pg, printed)}" if pg != last else "") + f" {t}"
                last = pg
            text += "".join(f" {marker(pg, printed)}" for pg in it.get("trail", []))
            blocks.append(("p", text))
        elif k == "h":
            root = ranks.index(root_size) if root_size in ranks else -1
            blocks.append(("h", "#" * min(6, max(2, 1 + ranks.index(it["size"]) - root)) + " " + it["text"]))
        elif k == "li":
            while stack and it["x"] < stack[-1] - 4:
                stack.pop()
            if not stack or it["x"] > stack[-1] + 4:
                stack.append(it["x"])
            blocks.append(("li", "  " * (len(stack) - 1) + f"{it['mark']} {it['text']}"))
        elif k == "fn":
            blocks.append(("fn", f"[^{it['n']}]: {it['text']}"))
        else:
            blocks.append((k, it["text"]))
        if k != "li":
            stack = []
        if k != "fn":
            page = it["page"]
    out = ""
    for i, (kind, text) in enumerate(blocks):
        out += ("" if not i else "\n" if kind == blocks[i - 1][0] and kind in ("li", "fn") else "\n\n") + text
    return out


def convert(pdf, root, book, title, credit="", skip=(), max_pages=14, head_min=14):
    doc = pymupdf.open(pdf)
    roots = outline(doc)
    units, skipped = plan(roots, {s.casefold() for s in skip}, max_pages)
    skipped_pages = {p for s in skipped for p in range(s.page, max(s.end, s.page + 1))}
    pages = [p for p in range(roots[0].page, doc.page_count + 1) if p not in skipped_pages]
    titles = {n.page: _norm(n.title) for n in roots if CHAPTER.match(n.title) and n not in skipped}
    stream, printed = build_stream(doc, pages, titles, head_min)
    ranks = sorted({i["size"] for i in stream if i["k"] == "h"}, reverse=True)

    starts, cursor, warns = [], 0, []
    for u in units:
        n = u["node"]
        if u["kind"] == "intro":
            s = next((i for i, it in enumerate(stream) if it["page"] >= n.page), len(stream))
        else:
            s = locate(stream, n, cursor)
            if s is None:
                s = next((i for i, it in enumerate(stream) if i >= cursor and it["page"] >= n.page), len(stream))
                warns.append(f"heading not found, started at the top of PDF p. {n.page}: {n.title}")
        starts.append(s)
        cursor = s + (u["kind"] != "intro")
    starts.append(len(stream))

    core, idx = Path(root) / "core" / book, Path(root) / "core" / book / "index.md"
    if core.exists():
        if not (idx.exists() and MARK in idx.read_text(encoding="utf-8")):
            sys.exit(f"{core} exists and was not generated by this script; refusing to overwrite it")
        shutil.rmtree(core)
    index, used, covered = {}, set(), set()
    for u, s, e in zip(units, starts, starts[1:]):
        items = stream[s:e]
        root_size, refs = None, ""
        if items and items[0]["k"] == "h" and u["kind"] != "intro":
            root_size, refs, items = items[0]["size"], "".join(re.findall(r"\[\^\d+\]", items[0]["text"])), items[1:]
        if not items:
            continue
        n = u["node"]
        name = {"intro": f"{n.title} (opening)", "lead": f"{n.title} (lead-in)"}.get(u["kind"], n.title)
        first, last = stream[s]["page"], items[-1]["page"]
        covered |= {it["page"] for it in items}
        rel = f"{u['folder']}/p{first:03d}-{'chapter-intro' if u['kind'] == 'intro' else slug(name)}.md"
        while rel in used:
            rel = rel[:-3] + "-2.md"
        used.add(rel)
        pg = str(first) if first == last else f"{first}-{last}"
        head = ["---", f"title: {json.dumps(name, ensure_ascii=False)}", f"book: {book}", f"chapter: {u['label']}",
                f'source_pages: "{pg}"', "format: source-text", "---", f"# {name}{refs}", f"(Source: {_span(first, last)})", ""]
        (core / rel).parent.mkdir(parents=True, exist_ok=True)
        (core / rel).write_text("\n".join(head) + "\n" + render(items, root_size, ranks, printed) + "\n", encoding="utf-8")
        index.setdefault(u["folder"], (u["top"], []))[1].append((name, rel, pg))
    blank = [p for p in pages if p not in covered]
    if blank:
        warns.append("no text on PDF pages " + ", ".join(map(str, blank)))

    lines = [f"# {title}: source text", "",
             f"{MARK}; do not edit. A plain-text conversion of the book's PDF, one file per outline section, grouped by "
             "chapter. It reproduces the book's own text; it is not a set of original-wording modules.", "",
             f"- Source: `{Path(pdf).name}` ({doc.page_count} PDF pages), SHA-256 "
             f"`{hashlib.sha256(Path(pdf).read_bytes()).hexdigest()}`." + (f" {credit}" if credit else ""),
             "- Every file carries page markers: `<!-- PDF p. N (book p. M) -->` (N = PDF page, M = printed page number). "
             "Cite the PDF page.",
             "- Tables are pipe tables. Figures, photographs and diagrams are not converted (`*[Figure omitted]*` marks "
             "the place; captions are kept). Footnotes are `[^n]` references with their text after the page.",
             "- Known limit: the PDF's own text layer is used. In some fonts (callout boxes and a few tables) it turns capital "
             "letters into lower case (for example `pCi Dss` for PCI DSS); the rendered page shows the right case.",
             f"- Regenerate: `python scripts/pdf_to_md.py <pdf> --book {book} --title \"{title}\""
             + (f" --skip \"{','.join(skip)}\"" if skip else "") + f" --max-pages {max_pages} --head-min {head_min}`.", ""]
    if roots[0].page > 1 or skipped:
        lines += ["## Not converted", ""]
        if roots[0].page > 1:
            lines.append(f"- {_span(1, roots[0].page - 1)}: cover, title page and copyright (no outline entry).")
        lines += [f"- {_span(s.page, max(s.end, s.page + 1) - 1)}: {s.title} (not converted)." for s in skipped] + [""]
    for folder, (top, rows) in index.items():
        lines += [f"## {top}", "", "| File | PDF pages |", "|---|---|"] + [f"| [{n}]({r}) | {p} |" for n, r, p in rows] + [""]
    if warns:
        lines += ["## Conversion warnings", ""] + [f"- {w}" for w in warns] + [""]
    idx.write_text("\n".join(lines), encoding="utf-8")
    return len(used), warns


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("pdf")
    ap.add_argument("--book", required=True, help="folder name under core/")
    ap.add_argument("--title", required=True)
    ap.add_argument("--credit", default="", help="author, publisher, year and licence line for index.md")
    ap.add_argument("--skip", default="", help="comma-separated top-level outline titles not to convert")
    ap.add_argument("--max-pages", type=int, default=14)
    ap.add_argument("--head-min", type=float, default=14, help="smallest heading size in points")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    a = ap.parse_args(argv)
    skip = [s.strip() for s in a.skip.split(",") if s.strip()]
    n, warns = convert(a.pdf, a.root, a.book, a.title, a.credit, skip, a.max_pages, a.head_min)
    print(f"pdf_to_md: {n} files in core/{a.book}/, {len(warns)} warning(s)")
    for w in warns:
        print("  warning:", w)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
