"""Convert a book PDF into plain Markdown under core/<book>/: a source-text conversion, not original-wording modules.

One file per outline section in one folder per chapter (a section longer than --max-pages is split along its
sub-sections), PDF page markers in every file, and a generated index.md. Tables become pipe tables. Figures are not
converted (a marker is left); figure text with a broken encoding is dropped and marked. Headers, footers and page
numbers are removed (the printed page number goes into the page marker).

Usage: python pdf_to_md.py <book.pdf> --book SLUG --title "Book title" [--credit TEXT] [--skip "Title,Title"]
                           [--max-pages 14] [--head-min 14] [--root DIR]
--skip names top-level outline entries that are not converted (contents, biographies, index ...).
Layout assumptions (checked on the book this was written for): the page number sits in the bottom margin and a
running title in the top margin (also on rotated pages, where the margins keep their raw position), body text is
smaller than --head-min and headings are at or above it.
Known limit: the text layer is used as it is. Where a PDF font maps capital letters to lower case (this book's
callout boxes and some tables), the lower case stays; the rendered page shows the right case.
"""
