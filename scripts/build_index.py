"""Generate core/ai-engineering-building-applications-with-foundation-models/index.md, core/ai-engineering-building-applications-with-foundation-models/concepts.md and core/ai-engineering-building-applications-with-foundation-models/xref.md from the matrix and module frontmatter.

Usage: python build_index.py [--root DIR] [--book NAME]
Without --book it indexes the original book under core/; with --book NAME it indexes
coverage/NAME/coverage-matrix.csv into core/NAME/. All three files are generated; edit the modules or the matrix, not these files.
"""
import sys
from pathlib import Path

from _common import core_dir, load_matrix, split_frontmatter

CHAPTER_TITLES = {
    "preface": "Preface", "front": "Front matter", "back": "Epilogue, Index and author",
    "1": "Chapter 1. Introduction to Building AI Applications with Foundation Models",
    "2": "Chapter 2. Understanding Foundation Models", "3": "Chapter 3. Evaluation Methodology",
    "4": "Chapter 4. Evaluate AI Systems", "5": "Chapter 5. Prompt Engineering",
    "6": "Chapter 6. RAG and Agents", "7": "Chapter 7. Finetuning", "8": "Chapter 8. Dataset Engineering",
    "9": "Chapter 9. Inference Optimization", "10": "Chapter 10. AI Engineering Architecture and User Feedback",
}
ORDER = ["front", "preface"] + [str(i) for i in range(1, 11)] + ["back"]


def _list(value):
    return [x.strip() for x in value.strip().strip("[]").split(",") if x.strip()]


def _rel(dest, book=None):
    prefix = f"core/{book}/" if book else "core/ai-engineering-building-applications-with-foundation-models/"
    if not book and not dest.startswith(prefix):
        prefix = "core/"
    return dest.removeprefix(prefix)


def _chapter_title(book, ch, first_row):
    """The original book keeps its fixed titles; other books use the first segment of the section path."""
    if book is None:
        return CHAPTER_TITLES.get(ch, ch)
    return {"front": "Front matter", "preface": "Preface", "back": "Back matter"}.get(ch) or first_row["section_path"].split(" > ")[0]


def collect(root, book=None):
    mods = {}
    for r in load_matrix(root, book):
        path = Path(root) / r["destination_file"]
        meta = {}
        if r["role"] != "NON_SUBSTANTIVE" and path.exists():
            meta, _ = split_frontmatter(path.read_text(encoding="utf-8"))
        mods[r["id"]] = {"row": r, "meta": meta, "has_module": bool(meta)}
    return mods


def build(root, book=None):
    root = Path(root)
    mods = collect(root, book)
    core = core_dir(root, book)
    core.mkdir(parents=True, exist_ok=True)
    chapters = ORDER if book is None else list(dict.fromkeys(m["row"]["chapter"] for m in mods.values()))

    # index.md
    out = ["# Index of modules", "",
           "Generated by `scripts/build_index.py`; do not edit. One row per matrix row. "
           "Open the module for the section you need; `concepts.md` finds modules by concept, "
           "`xref.md` shows how modules relate, and `front-back-matter/p932-index.md` maps the book's own Index "
           "terms to modules.", ""]
    for ch in chapters:
        rows = [m for m in mods.values() if m["row"]["chapter"] == ch]
        if not rows:
            continue
        out += [f"## {_chapter_title(book, ch, rows[0]['row'])}", "", "| Row | Module | PDF pages | Role | Concepts |", "|---|---|---|---|---|"]
        for m in rows:
            r, meta = m["row"], m["meta"]
            pages = r["start_page"] if r["start_page"] == r["end_page"] else f"{r['start_page']}-{r['end_page']}"
            if m["has_module"]:
                title = meta.get("title") or r["section_path"].split(" > ")[-1]
                link = f"[{title}]({_rel(r['destination_file'], book)})"
                concepts = ", ".join(_list(meta.get("concepts", "")))
            else:
                link = f"{r['section_path'].split(' > ')[-1]} (no module: {r['role_reason']})"
                concepts = ""
            out.append(f"| {r['id']} | {link} | {pages} | {r['role']} | {concepts} |")
        out.append("")
    (core / "index.md").write_text("\n".join(out), encoding="utf-8")

    # concepts.md
    by_concept = {}
    for rid, m in mods.items():
        for c in _list(m["meta"].get("concepts", "")):
            by_concept.setdefault(c, []).append(rid)
    out = ["# Concepts", "", "Generated by `scripts/build_index.py`. Each concept lists the modules tagged with it.", ""]
    for c in sorted(by_concept):
        out += [f"## {c}", ""]
        for rid in by_concept[c]:
            m = mods[rid]
            out.append(f"- [{rid}]({_rel(m['row']['destination_file'], book)}) {m['meta'].get('title', '')}")
        out.append("")
    (core / "concepts.md").write_text("\n".join(out), encoding="utf-8")

    # xref.md
    out = ["# Cross-references", "",
           "Generated by `scripts/build_index.py` from each module's `related` list: the sections a module depends on "
           "or feeds.", ""]
    for rid, m in mods.items():
        rel = _list(m["meta"].get("related", ""))
        if not rel:
            continue
        links = ", ".join(f"[{x}]({_rel(mods[x]['row']['destination_file'], book)})" for x in rel if x in mods)
        out.append(f"- [{rid}]({_rel(m['row']['destination_file'], book)}) {m['meta'].get('title', '')}: {links}")
    out.append("")
    (core / "xref.md").write_text("\n".join(out), encoding="utf-8")
    return len(mods), len(by_concept)


def main(argv):
    root = Path(argv[argv.index("--root") + 1]) if "--root" in argv else Path(__file__).resolve().parent.parent
    book = argv[argv.index("--book") + 1] if "--book" in argv else None
    n, c = build(root, book)
    print(f"build_index: {n} rows, {c} concepts")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
